/**
 * Customer-facing copy must not carry claims the product does not deliver.
 * Grep-style guard over marketing surfaces (see docs/PRO-VALUE-RECOMMENDATIONS.md for the audit).
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(import.meta.url), '..', '..', '..');
const walk = (p, out = []) => {
  const s = statSync(p);
  if (s.isDirectory()) for (const n of readdirSync(p)) walk(join(p, n), out);
  else if (/\.(tsx|ts)$/.test(p) && !/\.test\./.test(p)) out.push(p);
  return out;
};
const rel = (f) => relative(ROOT, f).replace(/\\/g, '/');
const read = (f) => readFileSync(f, 'utf8');

// Surfaces that sell or describe Pro / the product to visitors.
const MARKETING = [
  'src/app/pro', 'src/app/pricing', 'src/app/page.tsx', 'src/app/login', 'src/app/sportsbooks',
  'src/app/free-sports-picks', 'src/app/blog', 'src/app/daily-ai-picks', 'src/components/monetization',
  'src/components/pro', 'src/components/picks/YesterdayResults.tsx', 'src/components/seo',
].flatMap((p) => walk(join(ROOT, p)));

const FORBIDDEN = [
  [/200\+/, 'unverifiable "200+" capper count'],
  [/real-?time/i, '"real-time" (data refreshes by polling, no real-time delivery)'],
  [/early access/i, '"early access" (not implemented)'],
  [/5[- ]?min(ute)?s?\s+delay|no 5-min|pick delay/i, 'pick-delay claim (no delay exists in code)'],
  [/before lines move/i, '"before lines move" (not implemented)'],
  [/consistent profits?|guaranteed (profit|win)/i, 'profit/guarantee claim'],
  [/AI-powered trend analysis|AI trend analysis/i, 'trend analysis sold as a feature (/trends is Coming Soon)'],
  [/full capper leaderboard/i, 'leaderboard sold as Pro (it is public)'],
  [/generated by AI \(/i, 'model provenance we cannot verify'],
  [/updated daily at 9 AM/i, 'inaccurate blog schedule claim'],
];

for (const [re, why] of FORBIDDEN) {
  test(`no ${why} in marketing surfaces`, () => {
    const hits = MARKETING.filter((f) => re.test(read(f))).map(rel);
    assert.deepEqual(hits, []);
  });
}

test('"200+ cappers" appears nowhere in src', () => {
  const hits = walk(join(ROOT, 'src')).filter((f) => /200\+\s*(individual\s+)?cappers/i.test(read(f))).map(rel);
  assert.deepEqual(hits, []);
});

test('/pricing does not state MEGA/NUCLEAR capper thresholds', () => {
  assert.doesNotMatch(read(join(ROOT, 'src/app/pricing/page.tsx')), /\(\s*\d+\+\s*cappers\s*\)|\(10\+\)/);
});

test('free vs Pro comparison table matches code gating (no delay/early-access rows)', () => {
  const t = read(join(ROOT, 'src/components/monetization/ComparisonTable.tsx'));
  assert.doesNotMatch(t, /Pick delay|Early access|Full grades/);
});
